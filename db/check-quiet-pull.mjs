/**
 * يفحص أن النبضَ لا يُنهك القاعدة — ساعاتُ تشغيلِها مالٌ يُدفع.
 *
 *   npm run check:quiet
 *
 * وقعت هذه في ٢٧ أكتوبر ٢٠٢٦: توقّف النظامُ عن قبول الدخول، وحُجب عنه
 * ستّةُ أشخاص. ولم تكن العلّةُ في شفرةٍ ولا في كلمة مرور، بل أنّ
 * **حصّةَ حوسبةِ القاعدة نضبت** فصارت ترفض كلَّ اتصال.
 *
 * وأصلُ الاستنزاف أنّ المتصفّح كان يسأل الخادمَ كلَّ ثماني ثوانٍ، وكلُّ
 * سؤالٍ منها إحدى وعشرون استفسارةً للقاعدة: جلسةُ المستخدم، ثمّ كلُّ
 * مجموعةٍ من ثمانيَ عشرةَ واحدةً واحدة، ثمّ المحذوفات، ثمّ رقمُ آخر
 * تغيير. أي نحوُ تسعةِ آلافِ استفسارةٍ في الساعة لكلِّ تبويبٍ مفتوح —
 * فلا تنام القاعدةُ أبداً، وتعمل الشهرَ كلَّه سبعَ مئةٍ وعشرين ساعة.
 *
 * فيُحرس ثلاثةٌ هنا:
 *
 *   ١) **رقمُ التغيير يُقرأ أوّلاً** ويُردُّ السائلُ فارغاً إن لم يتغيّر
 *      شيء — فتصير النبضةُ استفسارةً واحدةً بدل عشرين. وأكثرُ النبضات
 *      لا تجد جديداً، فهذا وحده يحذف نحوَ خمسةٍ وتسعين في المئة.
 *
 *   ٢) **التبويبُ المخفيُّ لا يُسأل له الخادم** — والنظامُ يُقفل بعد
 *      دقيقتين من الإخفاء أصلاً، فنبضةٌ بعدها لا يراها أحدٌ وتُحسب
 *      على الشركة. ويستيقظ النبضُ بالظهور فلا يُنتظر ثلاثون ثانية.
 *
 *   ٣) **ما بين النبضتين ثلاثون ثانيةً لا ثمان** — وستّةُ أشخاصٍ في
 *      مكتبٍ واحدٍ لا يحتاجون ثماني ثوان.
 *
 * ويُفحص معها أنّ طريقَ الدخول **يقول** إذا سقطت القاعدة: كان يخرج
 * خمسَ مئةٍ بجسمٍ فارغ، فقرأ صاحبُ الشركة «تعذّر الدخول» ولم يعرف أنّ
 * العلّةَ في القاعدة لا في كلمته.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { createJiti } from "jiti";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");

let bad = 0;
const check = (label, ok, detail = "") => {
  if (!ok) bad++;
  console.log(`  ${ok ? "✓" : "✗"} ${label}${detail ? " — " + detail : ""}`);
};

/* وتُسوّى نهاياتُ السطور: ملفاتُ الشاشة بـCRLF، وشرطٌ يقسمها بـ«\n» يمرّ فارغاً */
const read = (p) =>
  fs.readFileSync(path.join(ROOT, p), "utf8").replace(/\r\n/g, "\n");

const sync = read("lib/sync.ts");
const loginRoute = read("app/api/auth/login/route.ts");

/* ------------------------------------------------------------------ */
/* ١) النبضةُ الصامتة: تُجرَّب على قاعدةٍ مصطنعةٍ تَعُدُّ ما يُسأل عنه   */
/* ------------------------------------------------------------------ */
console.log("\nوما لم يتغيّر لا يُسأل عنه:\n");

const jiti = createJiti(import.meta.url);
const { changesSince } = await jiti.import("../lib/server/writes.ts");

/** قاعدةٌ لا تحفظ شيئاً، وإنما تُسجّل كلَّ استعلامٍ يصلها */
const spyDb = (rev) => {
  const asked = [];
  return {
    asked,
    async query(sql) {
      asked.push(sql.replace(/\s+/g, " ").trim());
      if (/change_seq/.test(sql)) return { rows: [{ v: String(rev) }] };
      return { rows: [] };
    },
  };
};

/* لا شيء استجدّ — رقمُ الخادم كرقم السائل */
let db = spyDb(5);
let out = await changesSince(db, 5);
check(
  "نبضةٌ لا تجد جديداً استفسارةٌ واحدة",
  db.asked.length === 1,
  `${db.asked.length} استفسارة — وكانت عشرين`
);
check(
  "وهي قراءةُ رقم التغيير",
  /change_seq/.test(db.asked[0] ?? ""),
  db.asked[0] ?? "(لا شيء)"
);
check(
  "ويرجع الردُّ فارغاً برقمه",
  out.rev === 5 &&
    Object.keys(out.upserts).length === 0 &&
    Object.keys(out.deletes).length === 0,
  JSON.stringify(out)
);

/* ورقمٌ أعلى من رقم الخادم — لا يُسأل عنه شيءٌ أيضاً */
db = spyDb(5);
out = await changesSince(db, 9);
check(
  "ومن سأل برقمٍ أعلى لا يُنهك القاعدة",
  db.asked.length === 1 && out.rev === 5,
  `${db.asked.length} استفسارة`
);

/* وقد استجدّ شيء — فتُقرأ المجموعاتُ كلُّها */
db = spyDb(12);
out = await changesSince(db, 5);
check(
  "ونبضةٌ تجد جديداً تقرأ المجموعاتِ كلَّها",
  db.asked.length > 10,
  `${db.asked.length} استفسارة`
);
check(
  "ورقمُ التغيير يُقرأ قبلها لا بعدها",
  /change_seq/.test(db.asked[0] ?? ""),
  "فصفٌّ يُكتب أثناء القراءة كان رقمُه يَصِل ولا يَصِل صفُّه"
);
check(
  "ولا يُقرأ مرّتين",
  db.asked.filter((s) => /change_seq/.test(s)).length === 1,
  `${db.asked.filter((s) => /change_seq/.test(s)).length} مرّة`
);
check("والرقمُ المُرجَع هو المقروء", out.rev === 12, String(out.rev));

/* ------------------------------------------------------------------ */
/* ٢) السكونُ في الخفاء                                               */
/* ------------------------------------------------------------------ */
console.log("\nوالتبويبُ المخفيُّ لا يُسأل له الخادم:\n");

check(
  "النبضُ يسكن والتبويبُ مخفيّ",
  /document\.hidden\)\s*\{\s*schedulePull\(\);\s*return;/.test(sync),
  "فيُعاد الموعدُ ولا تُستهلك ساعةُ حوسبة"
);
check(
  "ويُحرس بوجود المستند",
  /typeof document !== "undefined" && document\.hidden/.test(sync),
  "فالفحوصُ تُشغّل الوحدةَ بلا متصفّح"
);
/*
  ويُقاس المعنى لا الحرف. كان هذا الشرطُ يُضمر نصَّ المستمع بعينه
  (`document.hidden || !syncEnabled()`)، فلمّا نُقل حرسُ الإشعال إلى
  `pullNow` أخفق الشرطُ ولا خللَ في الشفرة — في الجلسة نفسِها التي
  كُتب فيها. فالمقيسُ ثلاثةٌ: أنّ هناك مستمعاً للظهور، وأنّه يسأل
  الخادمَ، وأنّ السؤالَ محروسٌ بالمزامنة حيث وقع الحرس.
*/
const listener = (sync.match(
  /addEventListener\("visibilitychange",[\s\S]{0,260}?\}\);/
) ?? [])[0];
check(
  "ويستيقظ بالظهور",
  Boolean(listener) &&
    /document\.hidden\) return;/.test(listener) &&
    /pullNow\(\)/.test(listener),
  "فمن رجع إلى التبويب يرى ما استجدّ في حينه"
);
check(
  "والسؤالُ العاجلُ محروسٌ بالمزامنة",
  /export async function pullNow[\s\S]{0,200}?if \(!syncEnabled\(\)\) return;/.test(
    sync
  ),
  "فلا يُسأل الخادمُ والمزامنةُ مطفأة"
);
check(
  "ويُوصَل المستمعُ مرّةً واحدة",
  /let watchingVisibility = false;/.test(sync) &&
    /if \(watchingVisibility \|\| typeof document === "undefined"\) return;/.test(
      sync
    ),
  "فالتطويرُ يُعيد تحميل الوحدات فيُركَّب مرّتين لو لم يُحرَس"
);
check(
  "ويُنادى من بدء المزامنة",
  /schedulePull\(\);\s*\n\s*watchVisibility\(\);/.test(sync)
);

/* ------------------------------------------------------------------ */
/* ٣) ما بين النبضتين                                                  */
/* ------------------------------------------------------------------ */
console.log("\nوما بين النبضتين:\n");

const everyMs = Number(
  (sync.match(/const PULL_MS = ([0-9_]+);/) ?? [])[1]?.replace(/_/g, "")
);
check(
  "ثلاثون ثانيةً أو أكثر",
  everyMs >= 30_000,
  `${everyMs / 1000} ثانية — وكانت ثماني`
);
check(
  "ومكتوبٌ لِمَ مُدَّت",
  /ساعات[\s\S]{0,400}تشغيلها/.test(sync),
  "فمن قصّرها بعد سنةٍ يقرأ ما جرى قبل أن يفعل"
);

/* ------------------------------------------------------------------ */
/* ٤) وطريقُ الدخول يقول إذا سقطت القاعدة                              */
/* ------------------------------------------------------------------ */
console.log("\nوالدخولُ لا يسقط صامتاً:\n");

check(
  "خطأُ القاعدة يُلتقط",
  /try \{\s*outcome = await login\(/.test(loginRoute),
  "فكان الطريقُ يخرج خمسَ مئةٍ بجسمٍ فارغ"
);
check(
  "ويُقال إنّ العلّةَ ليست في كلمة المرور",
  /قاعدة البيانات لا تستجيب/.test(loginRoute) &&
    /ليست في كلمة مرورك/.test(loginRoute)
);
check(
  "وبرمزٍ يفرّق الخادمَ من الداخل",
  /status: 503/.test(loginRoute),
  "فـ401 تعني كلمةً خاطئة، و503 تعني خادماً ساقطاً"
);
check(
  "ولا يزيد على ذلك إفشاءً",
  !/اسم المستخدم غير موجود/.test(loginRoute),
  "فالرسالةُ لا تفرّق بين اسمٍ خاطئٍ وكلمةٍ خاطئة"
);

console.log(
  bad === 0
    ? "\n✓ النبضُ هادئ: ما لم يتغيّر لا يُسأل عنه، والمخفيُّ لا يُنهك قاعدةً تُحاسَب بالساعة"
    : `\n✗ ${bad} فحصاً أخفق`
);
process.exit(bad === 0 ? 0 : 1);
