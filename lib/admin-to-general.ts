/**
 * المصروفات الإدارية إلى «عام».
 *
 * قاعدة صاحب الشركة: ما كان على حسابات 6xxx (الإدارية والعمومية) يُقيَّد
 * على «عام». لكن ٢٨١ حركة سبقت القاعدة — من الإكسل — وهي على «مصروفات
 * مشتركة». وليست كلها خطأ، فرُوجعت واحدةً واحدة قبل النقل (١٧ سبتمبر ٢٠٢٦):
 *
 *   تنتقل إلى «عام»  ٢١٦ حركة · ٣٤٬٣٩٤٫١٣٥
 *     رواتب الموظفين، عمولات البنك، الإقامات وأذونات العمل والضمان الصحي،
 *     إيجار المكتب وإنترنته وهاتفه ونظافته، مستلزمات المكتب.
 *
 *   تبقى على «مصروفات مشتركة» — لأنها تخدم المواقع لا المكتب:
 *     سكن العمال وأكلهم وملابسهم، صيانة السيارات والمولد (6250)،
 *     المخالفات المرورية ورخص القيادة وطوابع المرور.
 *
 *   تبقى كما هي — بقرار صاحب الشركة:
 *     الكهرباء والماء (6220).
 *
 *   لا تُمسّ هنا لأن خطأها في الحساب لا في السلّة، وتُصحَّح كلٌّ وحدها:
 *     دفعة ألمنيوم على الرواتب، رسوم حدود قسيمة، صبغ سيارة على الرسوم.
 *
 * والحساب لا يتغيّر، والاعتماد لا يُمسّ. فلا يتغيّر ميزان المراجعة ولا
 * صافي الربح — يتغيّر أين تظهر الحركة في تقرير الربحية وحده.
 */

import type { Movement } from "./accounting";

const SHARED = "مصروفات مشتركة";

/** ما يخدم المواقع فيبقى مشتركاً */
const SERVES_SITES = /سكن العمال|سكن عمال|أكل عمال|اكل عمال|ملابس عمال|مخالفة مرورية|رخصة قيادة|طابع مرور/;

/** أخطاء حساب تُصحَّح وحدها — لا تُنقل مع السلّة */
const ACCOUNT_ERRORS = /لمونيوم|لمنيوم|ألمنيوم|لومنيوم|حدود قسيمة/;

export function isAdminExpenseToGeneral(m: Movement): boolean {
  if (m.project !== SHARED) return false;
  if (!String(m.debitCode).startsWith("6")) return false;

  const text = m.description ?? "";

  /* الصيانة (السيارات والمولد) والكهرباء والماء تبقى */
  if (m.debitCode === "6250" || m.debitCode === "6220") return false;

  if (SERVES_SITES.test(text)) return false;
  if (ACCOUNT_ERRORS.test(text)) return false;

  /* صبغ سيارة على الرسوم الحكومية: خطأ حساب */
  if (m.debitCode === "6260" && /سيار/.test(text)) return false;

  return true;
}
