/**
 * اليوم — بتوقيت الكويت.
 *
 * كان «اليوم» يُحسب من `toISOString()`، وذلك توقيت غرينتش. والكويت
 * تسبقه بثلاث ساعات، فما بين منتصف الليل والثالثة فجراً يكون اليوم
 * عندنا يوماً وعند النظام يومَ أمس.
 *
 * ولا يظهر هذا إلا لمن يعمل ليلاً — فتُقيَّد حركته بتاريخ أمس، وتُحسب
 * مقارنةُ المطابقة ليومٍ مضى فتكتب فوق حكمه. وكلاهما خطأٌ صامت: لا
 * رسالة ولا تنبيه، وإنما رقمٌ في غير موضعه يُكتشف بعد حين.
 *
 * والكويت لا تغيّر ساعتها صيفاً ولا شتاءً — ثلاث ساعاتٍ ثابتة منذ
 * ١٩٨٢ — فالإزاحة رقمٌ واحد لا جدول.
 *
 * واللحظات لا تُمَسّ: وقت الاعتماد ووقت الإنشاء تبقى بتوقيت غرينتش
 * كما تُكتب، فهي لحظاتٌ لا أيام. وإنما يُحوَّل ما يُسأل فيه «في أي
 * يومٍ وقع هذا؟».
 */

/** إزاحة الكويت عن غرينتش — ثابتة، لا توقيت صيفي */
export const KUWAIT_OFFSET_HOURS = 3;

const OFFSET_MS = KUWAIT_OFFSET_HOURS * 3600_000;

/** اليوم الذي وقعت فيه هذه اللحظة بتوقيت الكويت — YYYY-MM-DD */
export function dayOf(at: string | number | Date): string {
  const time = at instanceof Date ? at.getTime() : new Date(at).getTime();
  if (!Number.isFinite(time)) return "";
  return new Date(time + OFFSET_MS).toISOString().slice(0, 10);
}

/** اليوم — كما هو في الكويت الآن */
export const todayISO = (): string => dayOf(Date.now());

/**
 * الشهرُ الذي تُفتح عليه شاشةٌ تعمل بالشهور، داخل السنة المختارة.
 *
 * كانت شاشتا الحضور والرواتب تُفتحان على **يناير** أيّاً كان اليوم —
 * فمن أراد حضورَ هذا الشهر نزل إلى القائمة واختاره في كل مرة. وشكا
 * صاحب الشركة منه: «أريده أن يفتح على الشهر الذي أنا فيه، حتى أعرف
 * بلا تضييع وقتٍ حالَ الحضور وأضيف اليوم».
 *
 * ولا يُفتح على شهرٍ خارج السنة المختارة: من يراجع سنةً مضت لا يُقحَم
 * في شهرٍ ليس منها. فيُقصر شهرُ اليوم على حدّي تلك السنة — آخرُها لمن
 * مضت، وأوّلُها لمن لم تأتِ بعد.
 */
export function monthInYear(year: number): string {
  const today = todayISO();
  const thisYear = Number(today.slice(0, 4));
  if (year === thisYear) return today.slice(0, 7);
  return year < thisYear ? `${year}-12` : `${year}-01`;
}
