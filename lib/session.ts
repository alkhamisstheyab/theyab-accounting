/**
 * الجلسة في المتصفّح: ما يُحفظ منها وما لا يُحفظ.
 *
 * كانت شاشة الدخول تعرض أسماء الموظفين ليختار منها الداخل، فوجب أن
 * تصل قائمةُ المستخدمين كلَّ جهاز. فصار الاسم يُكتب لا يُختار — ولا
 * يعرف من فتح الصفحة من في الشركة.
 *
 * ويُحفظ الاسم في الجهاز وحده تيسيراً على صاحبه: من دخل من هاتفه
 * يجد اسمه مكتوباً في المرة التالية. **ولا تُحفظ كلمة المرور أبداً**،
 * لا هنا ولا في مكانٍ آخر — ومن جلس على جهاز غيره ضغط «غيّر المستخدم».
 *
 * والحفظ في تخزين المتصفّح: لا يُرسل إلى الخادم، ولا ينتقل إلى جهازٍ
 * آخر، ويُقرأ ويُكتب بين try/catch لأن التخزين قد يكون ممنوعاً في
 * نافذةٍ خاصة فلا يُوقف ذلك الدخول.
 */

const NAME_KEY = "theyab:last-user";
/*
  القفل يعبر تحديث الصفحة.

  كان في ذاكرة الصفحة وحدها، فمن وجد شاشةً مقفلة ضغط تحديثاً فدخل بلا
  كلمة مرور — والتصريح عند الخادم قائم، والذاكرة تُمحى بالتحديث. فصار
  يُكتب في الجهاز: يُقرأ عند الإقلاع فتُسدَل الستارة قبل أن يظهر شيء،
  ولا يُرفع إلا بكلمة صاحبه.
*/
const LOCK_KEY = "theyab:locked";
/*
  وقت آخر عملٍ لصاحب الجهاز.

  ومهلة السكون كانت تُقاس في الصفحة المفتوحة وحدها، فمن أغلق الموقع
  وعاد بعد ساعةٍ وجده مفتوحاً له: لا صفحةَ بقيت تعدّ غيبته، والتصريح
  عند الخادم قائمٌ أسبوعين. وذلك ينقض المقصود — الغيبة ساعةٌ أطول من
  ربع الساعة التي تُوجب القفل.

  فيُكتب الوقت هنا، ويُقاس عند الإقلاع: إن طالت الغيبة أُسدلت الستارة
  قبل أن يظهر شيء.
*/
const SEEN_KEY = "theyab:last-active";

/**
 * مهلة السكون على الحاسوب.
 *
 * ربع ساعة: لا يبلغها من يعمل — فقلبُ الفاتورة ومراجعة العقد ومكالمةٌ
 * تُجاب كلُّها عملٌ لا بطالة — ويبلغها من قام عن مكتبه ونسي. ولو
 * قصّرناها إلى دقيقةٍ لكتب الموظف كلمته على ورقةٍ بجانب الشاشة،
 * فتصير الحماية أضعف مما لو تركناها.
 */
export const IDLE_LOCK_MS = 15 * 60_000;

/**
 * مهلة غياب الصفحة على الهاتف.
 *
 * تغيب حين تُقفل شاشته أو يخرج إلى تطبيقٍ آخر. ودقيقتان تكفيان: من
 * خرج إلى الحاسبة ليقرأ رقماً ثم عاد لا يُطالَب بكلمته، ومن أغلق
 * هاتفه ووضعه في جيبه يُطالَب.
 */
export const HIDDEN_LOCK_MS = 2 * 60_000;

/** آخر من دخل من هذا الجهاز، أو فارغ */
export function lastUser(): string {
  try {
    return localStorage.getItem(NAME_KEY) ?? "";
  } catch {
    return "";
  }
}

/** يحفظ الاسم وحده — والكلمة لا تُحفظ */
export function rememberUser(name: string): void {
  try {
    localStorage.setItem(NAME_KEY, name);
  } catch {
    /* التخزين ممنوع — ويُكتب الاسم في كل مرة، ولا يمنع ذلك الدخول */
  }
}

/** أَقُفلت الشاشة قبل أن تُحدَّث أو تُغلق؟ */
export function wasLocked(): boolean {
  try {
    return localStorage.getItem(LOCK_KEY) === "on";
  } catch {
    /* لا تخزين — والقفل حينئذٍ لهذه الصفحة وحدها */
    return false;
  }
}

/** يُثبت القفل أو يرفعه — والإثبات قبل إسدال الستارة لا بعدها */
export function rememberLock(on: boolean): void {
  try {
    if (on) localStorage.setItem(LOCK_KEY, "on");
    else localStorage.removeItem(LOCK_KEY);
  } catch {
    /* لا تخزين — ويبقى القفل عاملاً في هذه الصفحة */
  }
}

/** يُثبت أن صاحبه يعمل الآن — يُكتب كل نصف دقيقة لا مع كل ضغطة */
export function touchActivity(): void {
  try {
    localStorage.setItem(SEEN_KEY, String(Date.now()));
  } catch {
    /* لا تخزين — فالقياس على الصفحة وحدها كما كان */
  }
}

/**
 * أطالت الغيبة حتى وجب القفل؟
 *
 * وأول فتحٍ للجهاز لا غيبة فيه — لا وقت محفوظ — فلا يُقفل، وصاحبه
 * داخلٌ بكلمته أصلاً.
 */
export function idleTooLong(): boolean {
  try {
    const raw = localStorage.getItem(SEEN_KEY);
    if (!raw) return false;
    const last = Number(raw);
    if (!Number.isFinite(last) || last <= 0) return false;
    return Date.now() - last >= IDLE_LOCK_MS;
  } catch {
    return false;
  }
}

/** «لستَ أنت؟» — يُنسى الاسم فيُفتح الحقل فارغاً */
export function forgetUser(): void {
  try {
    localStorage.removeItem(NAME_KEY);
  } catch {
    /* لا شيء يُمحى — ولا ضرر */
  }
}
