/** الأدلّةُ التي يملك صاحبُ هذه الصلاحيات أن يعمل بها */
export const guidesFor = (permissions: readonly Permission[]): Guide[] =>
  GUIDES.filter((g) => !g.needs || permissions.includes(g.needs));

/** مجموعاتُ الأدلّة بترتيب أوّل ظهورها */
export const guideGroups = (guides: Guide[]): string[] => {
  const seen: string[] = [];
  for (const g of guides) if (!seen.includes(g.group)) seen.push(g.group);
  return seen;
};
