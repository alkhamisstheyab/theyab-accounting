import type { Movement } from "./accounting";

/** دفعة ألمنيوم مقيّدة على الرواتب الإدارية */
export const isAluminiumOnSalaries = (m: Movement): boolean =>
  m.debitCode === "6110" && /لمونيوم|لمنيوم|ألمنيوم|لومنيوم/.test(m.description ?? "");

/** صبغ سيارة مقيّد على الرسوم الحكومية */
export const isCarPaintOnGovFees = (m: Movement): boolean =>
  m.debitCode === "6260" && /صبغ\s*سيار/.test(m.description ?? "");
